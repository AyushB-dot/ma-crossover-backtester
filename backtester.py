import yfinance as yf #downloads historical market data (like stock prices, dividends, and trading volume) directly from Yahoo Finance
import pandas as pd #library for working with structured data in tables (DataFrames), similar to an Excel spreadsheet in Python
import numpy as np #handles fast mathematical operations, arrays, and complex calculations like moving averages, standard deviations, or returns.
import matplotlib.pyplot as plt #• used to create charts and graphs.

df = yf.download("SPY", start="2021-01-01", end="2026-05-01", auto_adjust=True)

#df.head()

#Calculating Simple moving average(SMA) and Exponential moving average (EMA), both include a volatilty filter that will stay out of choppy markets

df["Market_Return"] = df["Close"].pct_change().fillna(0) #daily percentage returns of the stock, also replaces the first empty row with zero

#20-day annualized volatility filter (stay out of choppy markets above 25%)
#formula: [historical volatility = standard deviation of returns over a single period x sqrt of trading periods per yr]
df["Volatility"] = df["Market_Return"].rolling(window=20).std() * np.sqrt(252)
vol_threshold = 0.25

df["SMA_20"] = df["Close"].rolling(window=20).mean() #simple moving average over last 20 trading days
df["SMA_50"] = df["Close"].rolling(window=50).mean() #simple moving average over last 50 trading days

#when the 20 day average is higher than the 50 day average it means the stock is performing better than it has been in the past 50 days, so we buy. (1)
#when the 20 day average drops below the 50 day average that trend is down so it sells and sits in cash. (0)

#buy (1) if if SMA_20 > SMA_50 AND volatility < 25%, else sit in cash (0)
df["SMA_Signal"] = np.where((df["SMA_20"] > df["SMA_50"]) & (df["Volatility"] < vol_threshold), 1, 0)

#We only knows todays closing price after the market closes, so we cant trade on it till tommorow
#Shift down 1 row so we trade tomorrow based on today's closing price
df["SMA_Position"] = df["SMA_Signal"].shift(1).fillna(0)

# Trade column: (+1) = buy day, (-1) = sell day, (0) = no trade day
df["SMA_Trade"] = df["SMA_Position"].diff()

#EMA
df["EMA_20"] = df["Close"].ewm(span=20, adjust=False).mean()
df["EMA_50"] = df["Close"].ewm(span=50, adjust=False).mean()

#buy (1) if EMA_20 > EMA_50 AND volatility < 25%, else sit in cash (0)
df["EMA_Signal"] = np.where((df["EMA_20"] > df["EMA_50"]) & (df["Volatility"] < vol_threshold), 1, 0)
df["EMA_Position"] = df["EMA_Signal"].shift(1).fillna(0)
df["EMA_Trade"] = df["EMA_Position"].diff()

#Calculating how much a investment in this strategy would have grown over 5 years, and compare it to simply buying and holding the stock for the entire period

#starting investment value
Starting_Investment = 1

#daily returns of SMA and EMA
df["SMA_Return"] = df["SMA_Position"] * df["Market_Return"]
df["EMA_Return"] = df["EMA_Position"] * df["Market_Return"]

#Cumulative product, multiply day by day compounding returns starting from $1
df["Market_Equity"] = Starting_Investment * (1 + df["Market_Return"]).cumprod()

df["SMA_Equity"] = Starting_Investment * (1 + df["SMA_Return"]).cumprod()
df["EMA_Equity"] = Starting_Investment * (1 + df["EMA_Return"]).cumprod()

print(df[["Market_Equity", "SMA_Equity", "EMA_Equity"]].tail())

#How good or bad the strategy performed

def calculate_metrics(returns, equity):

  #grabs the last number in our equity tracker and calculates the percent gain based on our starting value
  total_return = ((equity.iloc[-1] / Starting_Investment) - 1) * 100

  #Calculate Sharpe Ratio
  sharpe_ratio = (returns.mean()/returns.std()) * np.sqrt(252)

  #Calculate Maximum Drawdown

  #track the highest value portfolio has reached each day
  rolling_peak = equity.cummax()

  #calculating how far below we are from the peak every day
  drawdown = (equity - rolling_peak) / rolling_peak

  #worst drop converted to a percentage
  max_drawdown = drawdown.min() * 100

  return {
    "Total Return (%)": round(float(total_return), 2),
    "Sharpe Ratio": round(float(sharpe_ratio), 2),
    "Max Drawdown (%)": round(float(max_drawdown), 2),
  }

sma_metrics = calculate_metrics(df["SMA_Return"], df["SMA_Equity"])
ema_metrics = calculate_metrics(df["EMA_Return"], df["EMA_Equity"])
market_metrics = calculate_metrics(df["Market_Return"], df["Market_Equity"])

print("SMA Strategy:", sma_metrics)
print("EMA Strategy:", ema_metrics)
print("Buy & Hold:  ", market_metrics)

